// Writes src/lib/domains/public-suffixes.ts from the Public Suffix List (ICANN section only),
// which the domain check uses to find the registrable part of a client's domain (E25).
// Run: node apps/platform/scripts/public-suffixes.mjs <path to public_suffix_list.dat>
// Source: https://publicsuffix.org/list/public_suffix_list.dat (Mozilla Public License 2.0).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) throw new Error("Pass the path of public_suffix_list.dat");
const text = readFileSync(source, "utf8");
const start = text.indexOf("// ===BEGIN ICANN DOMAINS===");
const end = text.indexOf("// ===END ICANN DOMAINS===");
if (start < 0 || end < 0) throw new Error("ICANN section not found");
const rules = text
  .slice(start, end)
  .split("\n")
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith("//"))
  // Internationalized rules: this step accepts ASCII domains only (punycode is refused).
  .filter((line) => /^[!*a-z0-9.-]+$/.test(line));
const today = new Date().toISOString().slice(0, 10);
const out = `// Generated by scripts/public-suffixes.mjs on ${today}: the ICANN section of the Public Suffix
// List (https://publicsuffix.org/list/public_suffix_list.dat), ASCII rules only, ${rules.length} rules.
// License: Mozilla Public License 2.0 (THIRD_PARTY_LICENSES.md). Server only: never import it in
// a page or component (it is about ${Math.round(rules.join("\\n").length / 1024)} KB).

export const PUBLIC_SUFFIX_RULES = ${JSON.stringify(rules.join(" "))};
`;
writeFileSync(
  fileURLToPath(new URL("../src/lib/domains/public-suffixes.ts", import.meta.url)),
  out,
);
console.log(`${rules.length} rules`);
